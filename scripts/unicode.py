#!/usr/bin/env python3
"""Generate crates/extract/src/unicode/tables.rs from the Unicode Character
Database: the tables hivepack-extract compares names with.

- Canonical combining classes, from UnicodeData.txt.
- Full canonical decompositions, from UnicodeData.txt, each expanded until
  nothing in it decomposes further. Hangul syllables are left out: their
  decompositions are computed.
- Simple case folding, the mappings of status C and S in CaseFolding.txt.

The database files are the `unicode-<VERSION>` set of testdata/manifest.json:

    python3 scripts/testdata.py fetch
    python3 scripts/unicode.py

The tables are written formatted by rustfmt. `cargo test -p
hivepack-extract` checks them against the same files, and Unicode's
NormalizationTest.txt.

Only the standard library is used, so any Python 3.9 or newer runs it.
"""

import os
import subprocess
import sys
from pathlib import Path

VERSION = "18.0.0"
ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "crates" / "extract" / "src" / "unicode" / "tables.rs"


def database() -> Path:
    cache = Path(os.environ.get("HIVEPACK_TESTDATA", ROOT / "target" / "testdata"))
    folder = cache / f"unicode-{VERSION}"
    if not (folder / ".complete").exists():
        raise SystemExit(f"{folder} is missing: run `python3 scripts/testdata.py fetch`")
    return folder


def code_points(field: str) -> list:
    return [int(cp, 16) for cp in field.split()]


def unicode_data(folder: Path):
    """The combining class of each character that has one other than 0,
    and the canonical decomposition mapping of each that has one. Ranges
    (`<..., First>`) have neither, and are skipped."""
    classes, mappings = {}, {}
    with (folder / "UnicodeData.txt").open(encoding="utf-8") as f:
        for line in f:
            fields = line.rstrip("\n").split(";")
            cp = int(fields[0], 16)
            if int(fields[3]):
                classes[cp] = int(fields[3])
            # A mapping with a <tag> is a compatibility one.
            if fields[5] and not fields[5].startswith("<"):
                mappings[cp] = code_points(fields[5])
    return classes, mappings


def full(cp: int, mappings: dict) -> list:
    if cp not in mappings:
        return [cp]
    return [d for part in mappings[cp] for d in full(part, mappings)]


def simple_folding(folder: Path) -> dict:
    folding = {}
    with (folder / "CaseFolding.txt").open(encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            code, status, mapping = [part.strip() for part in line.split(";")[:3]]
            if status in ("C", "S"):
                (to,) = code_points(mapping)
                folding[int(code, 16)] = to
    return folding


def char(cp: int) -> str:
    return "'\\u{%X}'" % cp


def ranges(classes: dict) -> list:
    """Runs of consecutive characters of one class."""
    runs = []
    for cp in sorted(classes):
        if runs and runs[-1][1] == cp - 1 and runs[-1][2] == classes[cp]:
            runs[-1][1] = cp
        else:
            runs.append([cp, cp, classes[cp]])
    return runs


def main() -> None:
    folder = database()
    classes, mappings = unicode_data(folder)
    folding = simple_folding(folder)

    decompositions = [(cp, full(cp, mappings)) for cp in sorted(mappings)]

    major, minor, update = VERSION.split(".")
    lines = [
        f"//! Generated by `scripts/unicode.py` from the Unicode Character Database",
        f"//! {VERSION}, under the Unicode License v3 (see `LICENSE-UNICODE`): do not",
        f"//! edit.",
        "",
        "/// The version of Unicode the tables are from.",
        f"pub const VERSION: (u8, u8, u8) = ({major}, {minor}, {update});",
        "",
        "/// Canonical combining classes other than 0, by runs of characters:",
        "/// the first, the last, and their class.",
        "pub(crate) static COMBINING: &[(char, char, u8)] = &[",
        *(f"    ({char(a)}, {char(b)}, {c})," for a, b, c in ranges(classes)),
        "];",
        "",
        "/// The characters with a canonical decomposition, Hangul syllables",
        "/// aside, each with its full decomposition.",
        "pub(crate) static DECOMPOSITIONS: &[(char, &[char])] = &[",
        *(f"    ({char(cp)}, &[{', '.join(map(char, d))}])," for cp, d in decompositions),
        "];",
        "",
        "/// Simple case folding: each character that folds, and what to.",
        "pub(crate) static FOLDING: &[(char, char)] = &[",
        *(f"    ({char(a)}, {char(b)})," for a, b in sorted(folding.items())),
        "];",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    subprocess.run(["rustfmt", "--edition", "2024", str(OUT)], cwd=ROOT, check=True)
    print(
        f"{OUT.relative_to(ROOT)}: Unicode {VERSION}, {len(ranges(classes))} runs of classes, "
        f"{len(decompositions)} decompositions, "
        f"{len(folding)} foldings",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
